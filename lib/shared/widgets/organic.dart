// ---------------------------------------------------------------------------
// Organic shape engine
// ---------------------------------------------------------------------------
//
// Every surface in EarnLens uses a fluid, asymmetric silhouette rather than a
// rounded rectangle. A shape is generated by sampling the perimeter of a
// rounded rectangle, pushing each sample along its outward normal by
//   * a low-frequency, seeded wave around the whole outline, and
//   * Gaussian "bumps" (swells or dips) placed on specific edges,
// then joining the samples with a closed Catmull-Rom spline. The result is
// deterministic for a given [BlobSpec] and size, always stays inside its
// bounds, and works anywhere a [ShapeBorder] does (clipping, ink, shadows).

enum BlobEdge { top, right, bottom, left }

/// A swell (positive [amount]) or dip (negative) on one edge. [at] is the
/// position along the edge (0 = left/top end), [spread] the width as a
/// fraction of that edge. Amounts are logical pixels at a 160 px tall shape
/// and scale down for smaller surfaces.
@immutable
class BlobBump {
  const BlobBump(this.edge, this.at, this.amount, {this.spread = 0.22});
  final BlobEdge edge;
  final double at;
  final double amount;
  final double spread;

  @override
  bool operator ==(Object other) =>
      other is BlobBump && other.edge == edge && other.at == at && other.amount == amount && other.spread == spread;

  @override
  int get hashCode => Object.hash(edge, at, amount, spread);
}

/// Describes an organic silhouette.
@immutable
class BlobSpec {
  const BlobSpec({
    this.radius = 30,
    this.radii,
    this.seed = 0,
    this.wobble = 0.6,
    this.wave,
    this.bumps,
    this.scaleWithSize = true,
  });

  /// Whether bump and wave amplitudes shrink on surfaces under 160 px.
  final bool scaleWithSize;

  /// Base corner radius (corners vary around it unless [radii] is given).
  final double radius;

  /// Explicit corner radii: top-left, top-right, bottom-right, bottom-left.
  final List<double>? radii;

  /// Varies the derived corners, waves and bumps.
  final int seed;

  /// Overall strength of the organic deformation (0 = plain rounded shape).
  final double wobble;

  /// Wave amplitude in px (defaults from [wobble]).
  final double? wave;

  /// Explicit bumps; derived from [seed] when null.
  final List<BlobBump>? bumps;

  double _rand(int i) {
    final x = math.sin((seed + 1) * 12.9898 + i * 78.233) * 43758.5453;
    return x - x.floorToDouble();
  }

  List<double> get cornerRadii =>
      radii ?? [for (var i = 0; i < 4; i++) radius * (0.78 + 0.5 * _rand(i))];

  double get waveAmplitude => wave ?? (1.2 + 2.6 * wobble);

  List<BlobBump> get effectiveBumps {
    if (bumps != null) return bumps!;
    if (wobble == 0) return const [];
    double sgn(int i) => _rand(i) > 0.42 ? 1 : -1;
    return [
      BlobBump(BlobEdge.top, 0.2 + 0.6 * _rand(20), sgn(21) * (5 + 6 * _rand(22)) * wobble, spread: 0.18 + 0.12 * _rand(23)),
      BlobBump(BlobEdge.bottom, 0.2 + 0.6 * _rand(24), sgn(25) * (4 + 6 * _rand(26)) * wobble,
          spread: 0.18 + 0.14 * _rand(27)),
      BlobBump(BlobEdge.right, 0.25 + 0.5 * _rand(28), (2 + 4 * _rand(29)) * wobble, spread: 0.3),
      BlobBump(BlobEdge.left, 0.25 + 0.5 * _rand(30), -(1 + 3 * _rand(31)) * wobble, spread: 0.3),
    ];
  }

  BlobSpec copyWith({double? radius, int? seed, double? wobble, List<BlobBump>? bumps}) => BlobSpec(
        radius: radius ?? this.radius,
        radii: radii,
        seed: seed ?? this.seed,
        wobble: wobble ?? this.wobble,
        wave: wave,
        bumps: bumps ?? this.bumps,
        scaleWithSize: scaleWithSize,
      );

  @override
  bool operator ==(Object other) =>
      other is BlobSpec &&
      other.radius == radius &&
      _listEq(other.radii, radii) &&
      other.seed == seed &&
      other.wobble == wobble &&
      other.wave == wave &&
      other.scaleWithSize == scaleWithSize &&
      _listEq(other.bumps, bumps);

  @override
  int get hashCode => Object.hash(radius, radii == null ? null : Object.hashAll(radii!), seed, wobble, wave,
      bumps == null ? null : Object.hashAll(bumps!), scaleWithSize);

  static bool _listEq<T>(List<T>? a, List<T>? b) {
    if (identical(a, b)) return true;
    if (a == null || b == null || a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }
}

/// Generates and caches organic paths.
abstract final class BlobPath {
  static final _cache = <(BlobSpec, int, int), Path>{};

  /// The organic outline of [spec] filling [rect].
  static Path of(BlobSpec spec, Rect rect) {
    if (rect.isEmpty) return Path()..addRect(rect);
    final key = (spec, (rect.width * 4).round(), (rect.height * 4).round());
    var p = _cache[key];
    if (p == null) {
      if (_cache.length > 160) _cache.remove(_cache.keys.first);
      p = _build(spec, rect.size);
      _cache[key] = p;
    }
    return p.shift(rect.topLeft);
  }

  static Path _build(BlobSpec spec, Size size) {
    final w = size.width, h = size.height;
    final scale = spec.scaleWithSize ? (math.min(w, h) / 160).clamp(0.3, 1.0) : 1.0;
    final wave = math.min(spec.waveAmplitude * scale, math.min(w, h) * 0.05);
    final bumps = [
      for (final b in spec.effectiveBumps) BlobBump(b.edge, b.at, b.amount * scale, spread: b.spread),
    ];

    // Inset each edge by its largest outward displacement so the outline
    // never leaves the bounds.
    double outward(BlobEdge e) =>
        wave + bumps.where((b) => b.edge == e && b.amount > 0).fold<double>(0, (m, b) => math.max(m, b.amount));
    final base = Rect.fromLTRB(outward(BlobEdge.left), outward(BlobEdge.top), w - outward(BlobEdge.right),
        h - outward(BlobEdge.bottom));
    if (base.width <= 4 || base.height <= 4) return Path()..addRRect(RRect.fromRectXY(Offset.zero & size, 12, 12));

    final maxR = math.min(base.width, base.height) / 2;
    final r = [for (final x in spec.cornerRadii) math.min(x, maxR)];

    // Perimeter samples (point + outward normal), clockwise from the top-left.
    final pts = <Offset>[];
    final normals = <Offset>[];
    final perimeter = 2 * (base.width + base.height);
    final step = (perimeter / 140).clamp(4.0, 10.0);
    void line(Offset a, Offset b, Offset n) {
      final len = (b - a).distance;
      final count = math.max(1, (len / step).ceil());
      for (var i = 0; i < count; i++) {
        pts.add(Offset.lerp(a, b, i / count)!);
        normals.add(n);
      }
    }

    void arc(Offset c, double rad, double from) {
      final count = math.max(2, (rad * math.pi / 2 / step).ceil());
      for (var i = 0; i < count; i++) {
        final a = from + (math.pi / 2) * i / count;
        final n = Offset(math.cos(a), math.sin(a));
        pts.add(c + n * rad);
        normals.add(n);
      }
    }

    final l = base.left, t = base.top, rt = base.right, b = base.bottom;
    line(Offset(l + r[0], t), Offset(rt - r[1], t), const Offset(0, -1));
    arc(Offset(rt - r[1], t + r[1]), r[1], -math.pi / 2);
    line(Offset(rt, t + r[1]), Offset(rt, b - r[2]), const Offset(1, 0));
    arc(Offset(rt - r[2], b - r[2]), r[2], 0);
    line(Offset(rt - r[2], b), Offset(l + r[3], b), const Offset(0, 1));
    arc(Offset(l + r[3], b - r[3]), r[3], math.pi / 2);
    line(Offset(l, b - r[3]), Offset(l, t + r[0]), const Offset(-1, 0));
    arc(Offset(l + r[0], t + r[0]), r[0], math.pi);

    // Seeded, closed-periodic wave (integer harmonics).
    double rnd(int i) => spec._rand(100 + i);
    final harmonics = [
      (2 + (rnd(0) * 2).floor(), 0.55 + 0.3 * rnd(1), rnd(2) * 2 * math.pi),
      (4 + (rnd(3) * 2).floor(), 0.3 + 0.2 * rnd(4), rnd(5) * 2 * math.pi),
      (7, 0.15, rnd(6) * 2 * math.pi),
    ];
    final norm = harmonics.fold<double>(0, (a, x) => a + x.$2);

    final n = pts.length;
    final out = List<Offset>.filled(n, Offset.zero);
    for (var i = 0; i < n; i++) {
      final p = pts[i], nm = normals[i];
      final u = i / n;
      var d = 0.0;
      for (final (k, a, ph) in harmonics) {
        d += a * math.sin(2 * math.pi * k * u + ph);
      }
      // Keep the wave mostly inward so straight edges read as gently concave.
      d = wave * (d / norm - 0.15);
      for (final bump in bumps) {
        final (affinity, along, span) = switch (bump.edge) {
          BlobEdge.top => (math.max(0.0, -nm.dy), (p.dx - l) / base.width, base.width),
          BlobEdge.bottom => (math.max(0.0, nm.dy), (p.dx - l) / base.width, base.width),
          BlobEdge.right => (math.max(0.0, nm.dx), (p.dy - t) / base.height, base.height),
          BlobEdge.left => (math.max(0.0, -nm.dx), (p.dy - t) / base.height, base.height),
        };
        if (affinity == 0 || span <= 0) continue;
        final z = (along - bump.at) / bump.spread;
        d += bump.amount * math.exp(-z * z * 2) * affinity * affinity;
      }
      final q = p + nm * d;
      out[i] = Offset(q.dx.clamp(0.0, w), q.dy.clamp(0.0, h));
    }

    // Closed Catmull-Rom spline through the displaced samples.
    final path = Path()..moveTo(out[0].dx, out[0].dy);
    for (var i = 0; i < n; i++) {
      final p0 = out[(i - 1 + n) % n], p1 = out[i], p2 = out[(i + 1) % n], p3 = out[(i + 2) % n];
      final c1 = p1 + (p2 - p0) / 6;
      final c2 = p2 - (p3 - p1) / 6;
      path.cubicTo(c1.dx, c1.dy, c2.dx, c2.dy, p2.dx, p2.dy);
    }
    return path..close();
  }
}

/// [ShapeBorder] for an organic silhouette described by a [BlobSpec].
class BlobBorder extends OutlinedBorder {
  const BlobBorder(this.spec, {super.side});
  final BlobSpec spec;

  @override
  BlobBorder copyWith({BorderSide? side}) => BlobBorder(spec, side: side ?? this.side);

  @override
  EdgeInsetsGeometry get dimensions => EdgeInsets.all(side.width);

  @override
  ShapeBorder scale(double t) => BlobBorder(spec.copyWith(radius: spec.radius * t), side: side.scale(t));

  @override
  Path getInnerPath(Rect rect, {TextDirection? textDirection}) => BlobPath.of(spec, rect.deflate(side.width));

  @override
  Path getOuterPath(Rect rect, {TextDirection? textDirection}) => BlobPath.of(spec, rect);

  @override
  void paint(Canvas canvas, Rect rect, {TextDirection? textDirection}) {
    if (side.style == BorderStyle.none || side.width == 0) return;
    canvas.drawPath(BlobPath.of(spec, rect.deflate(side.width / 2)), side.toPaint());
  }

  @override
  ShapeBorder? lerpFrom(ShapeBorder? a, double t) => a is BlobBorder ? (t < 0.5 ? a : this) : super.lerpFrom(a, t);

  @override
  ShapeBorder? lerpTo(ShapeBorder? b, double t) => b is BlobBorder ? (t < 0.5 ? this : b) : super.lerpTo(b, t);

  @override
  bool operator ==(Object other) => other is BlobBorder && other.spec == spec && other.side == side;

  @override
  int get hashCode => Object.hash(spec, side);
}

