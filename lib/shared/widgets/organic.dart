/// A filled organic surface: shape + colour or gradient, tinted glow shadow,
/// optional glossy sheen and glowing rim, optional lavender "aura" wave
/// peeking out behind it (the layered look of the reference cards), ink
/// response clipped to the silhouette, and inherited foreground colours.
class BlobSurface extends StatelessWidget {
  const BlobSurface({
    super.key,
    required this.spec,
    required this.child,
    this.color,
    this.gradient,
    this.shadows,
    this.sheen = 0,
    this.rim,
    this.aura,
    this.onTap,
    this.padding = EdgeInsets.zero,
    this.semanticLabel,
    this.foreground,
    this.backdrop,
  });

  final BlobSpec spec;
  final Widget child;
  final Color? color;
  final Gradient? gradient;
  final List<BoxShadow>? shadows;

  /// Strength (0–1) of the glossy highlight in the top-left.
  final double sheen;

  /// Glowing edge colour (painted as a soft gradient stroke).
  final Color? rim;

  /// Colour of a soft wave painted behind and slightly outside the surface.
  final Color? aura;
  final VoidCallback? onTap;
  final EdgeInsetsGeometry padding;
  final String? semanticLabel;

  /// Text/icon colour for descendants.
  final Color? foreground;

  /// Decorative painter clipped inside the surface, below content.
  final CustomPainter? backdrop;

  @override
  Widget build(BuildContext context) {
    final shape = BlobBorder(spec);
    Widget content = Padding(padding: padding, child: child);
    if (foreground != null) {
      content = DefaultTextStyle.merge(
        style: TextStyle(color: foreground),
        child: IconTheme.merge(data: IconThemeData(color: foreground), child: content),
      );
    }
    Widget surface = Material(
      type: MaterialType.transparency,
      shape: shape,
      clipBehavior: Clip.antiAlias,
      child: Ink(
        decoration: ShapeDecoration(shape: shape, color: gradient == null ? color : null, gradient: gradient),
        child: CustomPaint(
          painter: _SurfacePainter(spec, sheen: sheen, rim: rim, backdrop: backdrop),
          child: onTap == null ? content : InkWell(onTap: onTap, customBorder: shape, child: content),
        ),
      ),
    );
    if (shadows != null && shadows!.isNotEmpty) {
      surface = DecoratedBox(decoration: ShapeDecoration(shape: shape, shadows: shadows), child: surface);
    }
    if (aura != null) {
      surface = CustomPaint(painter: _AuraPainter(spec, aura!), child: surface);
    }
    return Semantics(button: onTap != null, label: semanticLabel, container: true, child: surface);
  }
}

class _SurfacePainter extends CustomPainter {
  _SurfacePainter(this.spec, {required this.sheen, this.rim, this.backdrop});
  final BlobSpec spec;
  final double sheen;
  final Color? rim;
  final CustomPainter? backdrop;

  @override
  void paint(Canvas canvas, Size size) {
    final rect = Offset.zero & size;
    final path = BlobPath.of(spec, rect);
    canvas.save();
    canvas.clipPath(path);
    backdrop?.paint(canvas, size);
    if (sheen > 0) {
      final c = Offset(size.width * 0.18, size.height * 0.08);
      final r = math.max(size.width, size.height) * 0.7;
      canvas.drawCircle(
        c,
        r,
        Paint()
          ..shader = RadialGradient(colors: [
            Colors.white.withValues(alpha: 0.65 * sheen),
            Colors.white.withValues(alpha: 0.18 * sheen),
            Colors.white.withValues(alpha: 0),
          ], stops: const [0, 0.45, 1])
              .createShader(Rect.fromCircle(center: c, radius: r)),
      );
    }
    canvas.restore();
    if (rim != null) {
      canvas.drawPath(
        BlobPath.of(spec, rect.deflate(0.75)),
        Paint()
          ..style = PaintingStyle.stroke
          ..strokeWidth = 1.5
          ..shader = LinearGradient(
            begin: Alignment.topLeft,
            end: Alignment.bottomRight,
            colors: [rim!, rim!.withValues(alpha: rim!.a * 0.15), rim!.withValues(alpha: rim!.a * 0.6)],
          ).createShader(rect),
      );
    }
  }

  @override
  bool shouldRepaint(_SurfacePainter old) =>
      old.spec != spec || old.sheen != sheen || old.rim != rim || old.backdrop != backdrop;
}

class _AuraPainter extends CustomPainter {
  _AuraPainter(this.spec, this.color);
  final BlobSpec spec;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    // Two soft wisps: one hugging the lower-left, one the right edge.
    final a = BlobPath.of(spec.copyWith(seed: spec.seed + 31, wobble: 1.2, bumps: const []),
        Rect.fromLTWH(-7, size.height * 0.35, size.width * 0.5, size.height * 0.7));
    final b = BlobPath.of(spec.copyWith(seed: spec.seed + 57, wobble: 1.2, bumps: const []),
        Rect.fromLTWH(size.width * 0.55, -5, size.width * 0.47 + 4, size.height * 0.8));
    final paint = Paint()..maskFilter = const MaskFilter.blur(BlurStyle.normal, 2);
    paint.shader = LinearGradient(
      begin: Alignment.bottomLeft,
      end: Alignment.topRight,
      colors: [color, color.withValues(alpha: 0)],
    ).createShader(Rect.fromLTWH(-7, size.height * 0.35, size.width * 0.5, size.height * 0.7));
    canvas.drawPath(a, paint);
    paint.shader = LinearGradient(
      begin: Alignment.topRight,
      end: Alignment.bottomLeft,
      colors: [color, color.withValues(alpha: 0)],
    ).createShader(Rect.fromLTWH(size.width * 0.55, -5, size.width * 0.47, size.height * 0.8));
    canvas.drawPath(b, paint);
  }

  @override
  bool shouldRepaint(_AuraPainter old) => old.spec != spec || old.color != color;
}

/// A tappable pastel bubble with an organic outline, glossy sheen, glowing
/// rim and a soft tinted shadow (quick actions, rate tiles, tinted stats).
class OrganicTile extends StatelessWidget {
  const OrganicTile({
    super.key,
    required this.child,
    required this.color,
    this.seed = 0,
    this.spec,
    this.onTap,
    this.padding = const EdgeInsets.all(AppSpace.lg),
    this.semanticLabel,
    this.gradient,
    this.glow,
  });

  final Widget child;
  final Color color;
  final int seed;

  /// Explicit silhouette (defaults to a seeded bubble).
  final BlobSpec? spec;
  final VoidCallback? onTap;
  final EdgeInsetsGeometry padding;
  final String? semanticLabel;
  final Gradient? gradient;

  /// Shadow tint (defaults to [color]).
  final Color? glow;

  @override
  Widget build(BuildContext context) {
    final dark = Theme.of(context).brightness == Brightness.dark;
    final g = gradient ??
        LinearGradient(
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
          colors: [Color.lerp(color, Colors.white, dark ? 0.04 : 0.55)!, color, Color.lerp(color, Colors.white, dark ? 0 : 0.2)!],
          stops: const [0, 0.55, 1],
        );
    final shadowColor = glow ?? color;
    return BlobSurface(
      spec: spec ?? BlobShapes.bubble(seed),
      gradient: g,
      sheen: dark ? 0.12 : 0.55,
      rim: Colors.white.withValues(alpha: dark ? 0.14 : 0.95),
      shadows: [
        BoxShadow(color: shadowColor.withValues(alpha: dark ? 0.2 : 0.32), blurRadius: 28, offset: const Offset(0, 8)),
        BoxShadow(color: Colors.white.withValues(alpha: dark ? 0 : 0.7), blurRadius: 6, offset: const Offset(-2, -2)),
      ],
      padding: padding,
      onTap: onTap,
      semanticLabel: semanticLabel,
      child: child,
    );
  }
}

